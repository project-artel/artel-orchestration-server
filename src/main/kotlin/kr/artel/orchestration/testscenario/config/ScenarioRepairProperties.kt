package kr.artel.orchestration.testscenario.config

import org.springframework.boot.context.properties.ConfigurationProperties

/**
 * 저작 결과를 코드가 얼마나 손보나(`artel.scenario.repair`).
 *
 * 지금 있는 것은 하나다 — **빈 구간을 코드가 메우나**.
 */
@ConfigurationProperties(prefix = "artel.scenario.repair")
data class ScenarioRepairProperties(

    /**
     * 두 케이스 사이가 안 이어지면 그 사이를 지도가 아는 조작으로 채운다.
     *
     * **끄고 재 볼 수 있어야 해서 설정으로 뺐다**(ARTEL-673). 이 메우기는 두 번 사고를 냈다.
     * 한 번은 한 칸을 살리려고 끼운 걸음이 두 칸 뒤를 죽였고(런 216, 시나리오 703), 또 한 번은
     * 어긋남 검사의 눈을 가렸다 — 실측(런 254)에서 `진행도 == 2` 케이스와 `진행도 == 1` 케이스
     * 사이에 타이틀 버튼을 누르는 걸음이 끼어 그 값을 다시 불러오게 만들었고, 검사는 그 자리에서
     * "이제 모른다"가 되어 바로 뒤의 어긋남을 못 짚었다. 같은 판에서 케이스 43스텝에 브리지가
     * 39스텝 붙었다.
     *
     * 켜 두면 예전 그대로다. 끄면 모델이 쓴 스텝만 남고, 못 이어지는 자리는 메우는 대신
     * 검사가 짚는다.
     */
    val bridges: Boolean = true,

    /**
     * 한 흐름에 담을 케이스 수의 상한.
     *
     * **한 판이 길수록 준비가 줄어든다**(ARTEL-679). 흐름이 끊길 때마다 다음 판은 게임 중간에서
     * 시작하게 되고, 실행하는 사람은 거기까지 다시 가야 한다 — 진행도 3을 만들려면 전투를 세 번
     * 이겨야 하는 식이다. 실측(런 263)에서 여섯 흐름 중 다섯이 못 이어서가 아니라 이 상한에
     * 걸려 끊겼다.
     *
     * 그렇다고 무한히 이으면 사람이 한 번에 돌릴 물건이 아니게 된다. 어디가 좋은지는 제품
     * 판단이라 설정으로 뺀다.
     *
     * **12·3 에서 20·6 으로 올렸다**(ARTEL-687). 케이스 83건으로 셋을 나란히 재 본 결과다:
     *
     * ```
     * 상한        판   지나갈 자리   어긋남   되물음   가장 큰 판   이름
     * 12 · 3     10        15         2       6        12건    구체적
     * 20 · 6      6        19         1       6        20건    구체적
     * 없음        4        22         3       6        64건    뭉툭
     * ```
     *
     * 판이 줄었는데 **어긋남이 오히려 줄었다.** 상한을 아예 없애면 모델이 계산이 준 64건짜리를
     * 그대로 한 시나리오로 내고(자르라고 적혀 있는데도 안 자른다) 이름이 뭉툭해진다 —
     * `전체 지도 진행과 엔딩까지`. 상한이 판을 나눠 주면서 이름이 구체적이 되던 것이 뜻밖의
     * 부수 효과였고, 그건 원래 모델이 할 일이다. 모델이 자르게 된 뒤에 다시 볼 자리다.
     *
     * 되물음은 셋 다 6건이다 — **질문 수는 상한과 무관하고 지도가 정한다.**
     */
    val maxCasesPerFlow: Int = 20,

    /** 한 흐름에 참을 수 있는 "지나갈 자리"(사람이 직접 플레이해야 하는 칸) 수의 상한. */
    val maxGapsPerFlow: Int = 6,
)
