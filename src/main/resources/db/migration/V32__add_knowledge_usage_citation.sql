-- knowledge_usage에 검색 경로(retrieval_kind)를 남기고, cited/step을 실제로 채우기 시작한다.
-- (2026-08-11, ARTEL-293)
--
-- V27이 만든 두 컬럼(cited, step)은 지금까지 항상 NULL이었다. 그 마이그레이션은 그렇게 될 것을
-- 알고 컬럼을 만들었고("채우는 것은 후속 작업이다"), 이 마이그레이션이 그 후속이다. 여기서
-- 바뀌는 것은 스키마 한 줄과 세 컬럼의 뜻이며, 채우는 코드는 애플리케이션에 있다.
--
-- 왜 지금인가. V27은 검색이 **무엇을 내보냈는지**를 기록한다. 그러나 그중 무엇이 실제로 쓰였는지는
-- 아무도 모른다. "만들었는데 아무도 안 꺼내 쓰는 지식"이 지식창고의 제일 흔한 실패인데, 검색
-- 로그만으로는 그것과 "꺼내 썼고 도움이 됐다"가 구분되지 않는다.
--
-- ⚠️ 기존 마이그레이션은 수정 금지(체크섬). 전부 새 버전으로 더한다.

--------------------------------------------------------------------------------
-- 1. retrieval_kind — 이 행이 어느 경로로 나갔나
--------------------------------------------------------------------------------
-- usage 행이 지금 세 출처로 섞여 들어온다:
--
--   DIRECT          질의에 직접 걸린 벡터 히트 (rank 1..N)
--   SEARCH_NEIGHBOR 그 히트에 딸려온 1홉 이웃 (rank null) — 에이전트가 요청하지 않았고, 밀어넣은 것
--   EXPAND          expand_knowledge 툴로 에이전트가 **직접 요청한** 이웃 (rank null)
--
-- 뒤의 둘이 rank null로 뭉개진다. 신호 세기가 다르다 — 밀어넣은 이웃을 안 쓰는 것은 정상이고,
-- 직접 요청해 놓고 안 쓴 것은 훨씬 강한 부정 신호다. 인용률의 분모가 이 구분에 달려 있다.
--
-- **rank로 유추하지 않는다.** 지금은 rank null이 이웃과 일치하지만, 새 검색 경로가 생기면 그
-- 유추는 조용히 틀린다. 값은 만드는 자리(KnowledgeRetrieval)에서 실어 오고, 공용 싱크인
-- recordRetrievals는 실린 값을 그대로 쓴다.
--
-- nullable이고 기본값이 없다. 기존 행은 출처를 **모르는** 것이지 DIRECT가 아니다 — 백필하지
-- 않는다. cited를 DEFAULT false로 두면 안 되는 것과 같은 판단이다.
--
-- **CHECK를 걸지 않는다.** 리포는 값 강제에 VARCHAR + CHECK를 쓰지만(qa_try.status,
-- knowledge.tag, knowledge_event.event), 그 셋은 전부 **Agent가 보낸 값이 흘러드는** 컬럼이라
-- DB가 마지막 방어선이다. 이 컬럼은 wire에서 오지 않는다: 값을 만드는 곳이 서버 코드뿐이고
-- 오타는 Kotlin enum이 컴파일에서 잡는다. 반대로 후속 검색 경로가 늘면 값도 늘어, CHECK가 있으면
-- 새 경로마다 마이그레이션이 코드 변경에 묶인다. 지키는 것이 없는 제약에 그 비용을 내지 않는다.
ALTER TABLE knowledge_usage
    ADD COLUMN IF NOT EXISTS retrieval_kind VARCHAR(20);

COMMENT ON COLUMN knowledge_usage.retrieval_kind IS
    'DIRECT(질의에 직접 걸린 히트) | SEARCH_NEIGHBOR(히트에 딸려 밀어넣은 1홉 이웃) | EXPAND(에이전트가 직접 요청한 이웃). NULL은 이 컬럼 이전에 기록된 행 — 출처를 모른다는 뜻이고 DIRECT가 아니다.';

--------------------------------------------------------------------------------
-- 2. step / cited — 뜻은 그대로, 이제 실제로 채워진다
--------------------------------------------------------------------------------
-- V27의 COMMENT는 "이번 범위에서는 항상 NULL"이라고 적어 두었다. 그 문장이 이제 거짓이 되므로
-- 여기서 고친다. 컬럼의 정의가 바뀌는 것은 아니다 — NULL의 뜻은 그대로 "모른다"이다.
COMMENT ON COLUMN knowledge_usage.step IS
    '검색이 난 시점의 런 스텝(Agent가 KNOWLEDGE_SEARCH/KNOWLEDGE_EXPAND payload에 싣는다). 기록되는 메타데이터이지 인용 매칭의 조인 키가 아니다 — 2번 스텝에서 검색한 것을 3번 스텝에서 인용하는 것은 정상 동작이다. NULL은 Agent가 싣지 않은 런.';

-- cited의 세 값은 V27이 정한 그대로다. 바뀐 것은 false가 **실제로 찍힌다**는 것뿐이다:
--   NULL  = 이 런은 인용을 보고할 수단이 없었다
--   false = 보고 가능했는데 인용하지 않았다  ← qa_try가 종단으로 갈 때 확정된다
--   true  = 인용했다
--
-- "보고할 수 있었던 런"의 판정은 추측이 아니라 기록으로 한다: Agent가 세션 개설 응답에
-- run_config.citation_reporting=true를 실어 주고, 확정 질의가 qa_try.run_config를 술어로 읽는다.
-- 그 표식이 없는 런은 영영 NULL이다 — 그것이 이 컬럼이 nullable인 이유 전부다.
--
-- ⚠️ **집계는 (런, 항목) 단위로 distinct 해야 한다.** 한 항목이 한 런에서 여러 번 검색됐으면
-- 그 행이 모두 true가 된다. 인용률이 묻는 것은 "이 런에서 썼나"이지 "몇 번 썼나"가 아니라,
-- 행을 그대로 세면 자주 검색된 항목이 유용해 보인다. knowledge_entry_facts의 citation_count는
-- (knowledge_id, version)당 행 수라 이 접기를 하지 않으므로, 비율을 내는 질의가 접어야 한다.
COMMENT ON COLUMN knowledge_usage.cited IS
    'NULL=인용을 보고할 수 없었던 런 / false=보고 가능했는데 인용하지 않음(qa_try 종단에서 확정) / true=이 런이 판정에 썼다고 스스로 보고. 자기신고라 과소보고로 치우친다. 비율은 (런, 항목) 단위로 distinct해서 낼 것.';
