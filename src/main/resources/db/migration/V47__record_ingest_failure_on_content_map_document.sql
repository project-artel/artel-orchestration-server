-- V47. 적재가 왜 실패했는지 문서에 적는다
--------------------------------------------------------------------------------
-- V41 이 만든 content_map_document 는 성공만 적을 수 있다 — `ingested_by` · `ingested_at` 뿐이다.
-- 실패하면 적재가 트랜잭션째 되돌아가고 문서는 `ingested_at IS NULL` 인 채로 남아, **아무 일도
-- 없었던 것과 똑같은 모양**이 된다. 사람이 화면에서 "왜 안 됐나"를 물을 자리가 없다.
--
-- 담는 것은 둘뿐이다. 시도 횟수 칸은 넣지 않는다 — 지금 이 저장소에는 자동 적재 경로가 없고
-- (스케줄러 없음, `findPending` 의 프로덕션 호출자 0), 버튼 경로는 상한을 일부러 무시한다.
-- 포기 임계값은 실제 실패를 보기 전에 아무도 못 고르는 정책 숫자이기도 하다. 큐 순서와 백오프는
-- 스케줄러를 만드는 이슈가 이 칸들 위에 얹는다.

-- 마지막 실패 시각. 성공하면 그대로 남는다 — "예전에 한 번 실패했지만 지금은 앉아 있다"는 사실이
-- 지워지지 않아야, 같은 문서가 되풀이해 깨지는 것을 나중에 알아볼 수 있다.
ALTER TABLE content_map_document
    ADD COLUMN IF NOT EXISTS ingest_failed_at TIMESTAMP WITH TIME ZONE;

-- 마지막 실패 사유. 화면이 사람에게 보여 줄 유일한 단서다.
--
-- 폭을 512 로 두고 넘치면 자른다. 스택 트레이스를 담는 칸이 아니다 — 그것은 로그의 몫이고, 여기
-- 필요한 것은 "무엇 때문에 못 앉았나" 한 줄이다.
ALTER TABLE content_map_document
    ADD COLUMN IF NOT EXISTS ingest_error VARCHAR(512);
