-- V78 — 전제를 문장이 아니라 구조로 (ARTEL-627)
--------------------------------------------------------------------------------
-- `test_case.precondition` 은 **한 문자열이 두 역할을 겸하고 있었다.**
--
--   사람이 읽는 표      Map_scene 화면인 상태 / MapMove.StagePosition >= 1 그리고 …
--   기계가 읽는 입력    같은 문자열을 정규식으로 되읽는다
--
-- 둘이 서로를 인질로 잡는다. 읽기 좋게 다듬으면 기계가 깨지고, 기계를 위해 정보를 남기면 문장이
-- 못생겨진다. 실측에서 셋 다 그 증상이었다:
--
--   `CombineButton.combineZone.activeSelf`  → 짧게 쓰려고 마지막 마디만 남겨 주인을 잃었다
--   `== 5 또는 == 4`                        → 공통 비교만 남겨 자리를 못 말하게 됐다
--   `(MapMove.StagePosition - 1)`           → 보여줄 방법이 없어 식으로만 남았다
--
-- 그런데 **원본은 처음부터 구조였다.** `capability_evidence.condition_tree` 가 1981행 전부에
-- 있고, 생성기는 그 트리를 손에 들고 있다가 문장으로 렌더해 버렸다. 새 생성기를 만든 이유가
-- 문자열 맞춤을 없애는 것이었는데, 그 아래 표가 옛 명세 시절 모양이라 거기서 다시 문자열이 됐다.
--
-- 그래서 구조를 그대로 싣는다. `precondition` 은 **화면에 보여주기 전용**으로 격하한다 —
-- 사용자에게 보이는 세 칸(사전조건·기능·기대결과)은 그대로 두라는 것이 계약이고, 그 계약은
-- 표시에 관한 것이지 저장에 관한 것이 아니다.
--
-- NULL 을 허용한다. 구버전 엑셀 경로로 들어온 행에는 트리가 없고, 없는 것을 빈 트리로 적으면
-- "조건 없음"과 "모름"이 같은 값이 된다.
ALTER TABLE test_case
    ADD COLUMN IF NOT EXISTS condition JSONB;

COMMENT ON COLUMN test_case.condition IS
    '사전조건의 구조(ConditionNode). precondition 문자열은 이것을 사람 말로 렌더한 표시용이다. 되짚을 트리가 없으면 NULL.';
