--------------------------------------------------------------------------------
-- test_case.metadata ->> 'case_key' 인덱스를 btree 에서 hash 로 바꾼다(ARTEL-1187).
--
-- btree 는 인덱스 한 행이 2,704바이트를 넘으면 그 INSERT 를 실패시킨다(압축한 뒤의 크기로 잰다). 갈래가 많은 기능의
-- case_key 는 기능 키 · 효과 · 조건 서명을 이어 붙여 길어지고, 2026-10-21 project 1 · 1.4.0 의 한 케이스가
-- 4,368바이트여서 TC 생성 트랜잭션 전체가 롤백됐다.
--
-- 키를 줄이지 않는 이유: 이보다 짧은 키는 지금까지 저장됐고, 다시 만들 때 그 키로 같은 케이스를 찾는다. 키를
-- 바꾸면 기존 케이스가 지워지고 새로 생겨 판정이 끊긴다.
--
-- hash 인덱스는 값의 해시만 담아 길이 제한이 없고, 같은지 묻는 조회에 쓰인다. 한 칸짜리라 project_id 는 뺀다.
-- 지금 이 칸으로 찾는 앱 질의는 없다(writer 는 프로젝트의 행을 읽어 메모리에서 맞춘다). V103 이 말한 build 를
-- 가로지른 조회가 생기면 이 인덱스가 같은지 비교를 받는다.
--------------------------------------------------------------------------------

DROP INDEX IF EXISTS idx_test_case_case_key;

CREATE INDEX IF NOT EXISTS idx_test_case_case_key
    ON test_case USING hash ((metadata ->> 'case_key'))
    WHERE (metadata ->> 'case_key') IS NOT NULL;
