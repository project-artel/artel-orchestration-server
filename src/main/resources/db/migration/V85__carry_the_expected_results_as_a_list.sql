-- V85 — 기대결과를 한 문장이 아니라 목록으로 (ARTEL-681 의 꼬리)
--------------------------------------------------------------------------------
-- `test_case.expected_value` 가 여러 개를 ` / ` 로 이어 한 칸에 담고 있다. 실측(word-venture,
-- 2026-09-01 지도) 85건 중 **19건이 2~5개**를 들고, 그 안의 항목이 53개다:
--
--   아무 키나 눌러 `AnyKeyPrompt` 의 표시 상태를 바꾼다 외 4건
--     → 프롬프트 토글 / chatName 갱신 / chatText 갱신 / 배경 하나 켜짐 / 배경 하나 꺼짐
--
-- 그런데 실행 쪽 판정은 스텝마다 `passed` 불리언 **하나**다(`report_step`). 다섯 중 넷만 나도
-- 통과로 적히고, 어느 것이 안 났는지 적을 자리가 없다.
--
-- `precondition` 이 겪은 것과 같은 병이다(V78). 생성기는 목록을 손에 들고 있다가 이어 붙여
-- 버렸고, 쓰는 쪽은 ` / ` 로 다시 쪼개야 한다 — 그 구분자가 기대결과 문장 안에 섞이는 날
-- 조용히 어긋난다. 문장은 표시 전용으로 두고 구조를 함께 싣는다.
--
-- NULL 을 허용한다. 구버전 엑셀 경로로 들어온 행과 이 컬럼 이전의 행에는 목록이 없고, 없는 것을
-- 빈 배열로 적으면 "기대결과 없음"과 "모름"이 같은 값이 된다.
ALTER TABLE test_case
    ADD COLUMN IF NOT EXISTS expected_items JSONB;

COMMENT ON COLUMN test_case.expected_items IS
    '기대결과 항목 목록(문자열 배열). expected_value 는 이것을 " / " 로 이어 보여주는 표시용이다. 목록을 모르면 NULL.';
